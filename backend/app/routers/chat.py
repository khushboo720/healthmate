"""AI health chatbot: history, messages, term explainer."""
import sqlite3

from fastapi import APIRouter, Depends
from pydantic import BaseModel, Field

from .. import ai
from ..db import get_db, rows
from ..knowledge import DEFAULT_CHAT, GLOSSARY, TOPICS
from ..safety import DISCLAIMER, detect_emergency, emergency_reply, is_personal, redact
from ..security import current_user

router = APIRouter(prefix="/api/chat", tags=["chat"])

DEMO_LABEL = "Demo mode: this is a pre-written educational answer, not generated by a live AI model."
WELCOME = ("Hello! Welcome to HealthMate AI. I can help you understand general health information, manage your health "
           "records and maintain healthy habits. How can I help you today?")


class ChatIn(BaseModel):
    message: str = Field(min_length=1, max_length=1000)


class TermIn(BaseModel):
    term: str = Field(min_length=2, max_length=80)


def demo_answer(text: str) -> str:
    low = text.lower()
    for words, answer in TOPICS:
        if any(w in low for w in words):
            return answer
    for term, meaning in GLOSSARY.items():
        if term in low:
            return f"**{term.title()}**: {meaning}"
    return DEFAULT_CHAT


@router.get("/history")
def history(user: dict = Depends(current_user), db: sqlite3.Connection = Depends(get_db)):
    msgs = rows(db, "SELECT id, role, content, mode, emergency, created_at FROM chat_messages WHERE user_id=? ORDER BY id", (user["id"],))
    return {"welcome": WELCOME, "messages": msgs, "ai": ai.status(), "disclaimer": DISCLAIMER}


@router.delete("/history")
def clear_history(user: dict = Depends(current_user), db: sqlite3.Connection = Depends(get_db)):
    db.execute("DELETE FROM chat_messages WHERE user_id=?", (user["id"],))
    db.commit()
    return {"ok": True}


@router.post("")
def send(body: ChatIn, user: dict = Depends(current_user), db: sqlite3.Connection = Depends(get_db)):
    text = body.message.strip()
    flags = detect_emergency(text)
    emergency = False
    mode = "demo"
    note = ""

    if flags and is_personal(text):
        # Safety first: respond immediately, never call the AI or ask follow-up questions.
        reply, mode, emergency = emergency_reply(flags), "safety", True
    else:
        prefix = ""
        if flags:  # general question that mentions a red-flag topic
            prefix = ("*If you or someone near you is having these symptoms right now, call your emergency number "
                      "(India 112 / 108, US 911) instead of reading this.*\n\n")
            emergency = True
        reply = None
        if ai.ai_enabled():
            # Only the user's question + the last few turns go to the AI. No name, email or profile data.
            recent = rows(db, "SELECT role, content FROM chat_messages WHERE user_id=? ORDER BY id DESC LIMIT 6", (user["id"],))[::-1]
            msgs = [{"role": m["role"], "content": redact(m["content"])} for m in recent] + [{"role": "user", "content": redact(text)}]
            try:
                reply, mode = prefix + ai.generate(msgs), "live"
            except ai.AIError:
                note = "\n\n_The live AI service could not be reached, so a demo answer is shown instead._"
        if reply is None:
            reply = prefix + demo_answer(text) + note
            mode = "demo"

    db.execute("INSERT INTO chat_messages (user_id, role, content) VALUES (?,?,?)", (user["id"], "user", text))
    cur = db.execute("INSERT INTO chat_messages (user_id, role, content, mode, emergency) VALUES (?,?,?,?,?)",
                     (user["id"], "assistant", reply, mode, int(emergency)))
    db.commit()
    return {"id": cur.lastrowid, "reply": reply, "mode": mode, "emergency": emergency,
            "demo_label": DEMO_LABEL if mode == "demo" else None, "disclaimer": DISCLAIMER}


@router.post("/explain-term")
def explain_term(body: TermIn, user: dict = Depends(current_user)):
    term = body.term.strip()
    key = term.lower()
    if ai.ai_enabled():
        try:
            text = ai.generate([{"role": "user", "content":
                f"Explain the medical term '{redact(term)}' in simple language in under 80 words. General information only."}], max_tokens=300)
            return {"term": term, "explanation": text, "mode": "live"}
        except ai.AIError:
            pass
    if key in GLOSSARY:
        return {"term": term, "explanation": GLOSSARY[key], "mode": "demo"}
    return {"term": term, "mode": "demo",
            "explanation": "This term is not in the built-in demo glossary. Try a common term such as hemoglobin, hypertension or BMI, or ask your doctor."}
