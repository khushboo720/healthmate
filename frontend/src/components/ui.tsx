export function ModeBadge({ mode }: { mode?: string | null }) {
  if (!mode) return null
  const live = mode === 'live'
  const safety = mode === 'safety'
  return (
    <span
      title={live ? 'Generated by a live AI model' : safety ? 'Built-in safety rule (no AI used)' : 'Pre-written demo content. Not generated by an AI model.'}
      className={`inline-flex items-center rounded-full px-2 py-0.5 text-[10px] font-bold uppercase tracking-wide ${
        live ? 'bg-emerald-100 text-emerald-800' : safety ? 'bg-red-100 text-red-800' : 'bg-amber-100 text-amber-800'
      }`}
    >
      {live ? 'Live AI' : safety ? 'Safety rule' : 'Demo mode'}
    </span>
  )
}

export function useAsync<T>(fn: () => Promise<T>, deps: unknown[] = []) {
  const [data, setData] = useState<T | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [loading, setLoading] = useState(true)
  const [tick, setTick] = useState(0)
  useEffect(() => {
    let alive = true
    setLoading(true)
    fn().then((d) => alive && (setData(d), setError(null)))
      .catch((e: Error) => alive && setError(e.message))
      .finally(() => alive && setLoading(false))
    return () => { alive = false }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [...deps, tick])
  return { data, error, loading, reload: () => setTick((t) => t + 1), setData }
}

// Minimal safe markdown: bold, italic, "- " bullets and paragraphs. No raw HTML is ever rendered.
function inline(text: string): ReactNode[] {
  return text.split(/(\*\*[^*]+\*\*|\*[^*]+\*|_[^_]+_)/g).map((part, i) => {
    if (part.startsWith('**') && part.endsWith('**') && part.length > 4) return <strong key={i}>{part.slice(2, -2)}</strong>
    if ((part.startsWith('*') && part.endsWith('*') || part.startsWith('_') && part.endsWith('_')) && part.length > 2) return <em key={i}>{part.slice(1, -1)}</em>
    return part
  })
}
export function Markdown({ text }: { text: string }) {
  const blocks: ReactNode[] = []
  let list: string[] = []
  const flush = () => {
    if (list.length) blocks.push(<ul key={`l${blocks.length}`} className="my-1 list-disc space-y-0.5 pl-5">{list.map((li, i) => <li key={i}>{inline(li)}</li>)}</ul>)
    list = []
  }
  text.split('\n').forEach((line) => {
    if (/^\s*[-•]\s+/.test(line)) list.push(line.replace(/^\s*[-•]\s+/, ''))
    else {
      flush()
      if (line.trim()) blocks.push(<p key={`p${blocks.length}`} className="my-1">{inline(line)}</p>)
    }
  })
  flush()
  return <>{blocks}</>
}

export function Field({ label, children, hint }: { label: string; children: ReactNode; hint?: string }) {
  return (
    <label className="block">
      <span className="label">{label}</span>
      {children}
      {hint && <span className="mt-1 block text-[11px] text-slate-500">{hint}</span>}
    </label>
  )
}

export function ConfirmButton({ onConfirm, children, className = 'btn-ghost btn-sm', message = 'Are you sure?' }:
  { onConfirm: () => void; children: ReactNode; className?: string; message?: string }) {
  return <button type="button" className={className} onClick={() => window.confirm(message) && onConfirm()}>{children}</button>
}
