import { useCallback, useEffect, useRef, useState, type FormEvent } from 'react'
import { useSearchParams } from 'react-router-dom'
import { Bot, Mic, Send, Trash2, User as UserIcon, Volume2, VolumeX } from 'lucide-react'
import { api, type AiStatus, type ChatMsg } from '../api'
import { ConfirmButton, Disclaimer, ErrorBox, Markdown, ModeBadge, PageHeader } from '../components/ui'

const SUGGESTED = [
  'Why do people experience headaches?',
  'What are common symptoms of dehydration?',
  'What is the importance of vitamin D?',
  'How can I improve my sleep?',
  'What are common causes of a sore throat?',
]
const DEMO_NOTE = 'Demo mode: pre-written educational answer, not generated by a live AI model.'

interface History { welcome: string; messages: ChatMsg[]; ai: AiStatus; disclaimer: string }
interface Reply { id: number; reply: string; mode: string; emergency: boolean; disclaimer: string }

// Web Speech API typings are not in lib.dom for all browsers
type SpeechRec = { start(): void; stop(): void; lang: string; interimResults: boolean; onresult: ((e: { results: ArrayLike<ArrayLike<{ transcript: string }>> }) => void) | null; onend: (() => void) | null; onerror: (() => void) | null }

export default function Chat() {
  const [params, setParams] = useSearchParams()
  const [welcome, setWelcome] = useState('')
  const [msgs, setMsgs] = useState<ChatMsg[]>([])
  const [ai, setAi] = useState<AiStatus | null>(null)
  const [disclaimer, setDisclaimer] = useState('')
  const [input, setInput] = useState('')
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [listening, setListening] = useState(false)
  const [speakingId, setSpeakingId] = useState<number | null>(null)
  const endRef = useRef<HTMLDivElement>(null)
  const recRef = useRef<SpeechRec | null>(null)
  const sentQ = useRef(false)

  useEffect(() => { endRef.current?.scrollIntoView({ behavior: 'smooth' }) }, [msgs, busy])

  const send = useCallback(async (text: string) => {
    const t = text.trim()
    if (!t || busy) return
    setError(null); setInput(''); setBusy(true)
    setMsgs((m) => [...m, { id: -Date.now(), role: 'user', content: t, mode: '', emergency: 0 }])
    try {
      const r = await api<Reply>('/api/chat', { body: { message: t } })
      setMsgs((m) => [...m, { id: r.id, role: 'assistant', content: r.reply, mode: r.mode, emergency: r.emergency ? 1 : 0 }])
    } catch (e) {
      setError((e as Error).message)
    } finally {
      setBusy(false)
    }
  }, [busy])

  useEffect(() => {
    api<History>('/api/chat/history').then((h) => {
      setWelcome(h.welcome); setMsgs(h.messages); setAi(h.ai); setDisclaimer(h.disclaimer)
      const q = params.get('q')
      if (q && !sentQ.current) { sentQ.current = true; setParams({}, { replace: true }); send(q) }
    }).catch((e: Error) => setError(e.message))
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [])

  const SR = (window as unknown as { SpeechRecognition?: new () => SpeechRec; webkitSpeechRecognition?: new () => SpeechRec })
  const Recognition = SR.SpeechRecognition ?? SR.webkitSpeechRecognition

  function toggleMic() {
    if (!Recognition) return
    if (listening) { recRef.current?.stop(); return }
    const r = new Recognition()
    r.lang = 'en-IN'; r.interimResults = false
    r.onresult = (e) => setInput(Array.from(e.results).map((x) => x[0].transcript).join(' '))
    r.onend = () => setListening(false)
    r.onerror = () => { setListening(false); setError('Voice input failed or was blocked. Please type your question.') }
    recRef.current = r; setListening(true); r.start()
  }

  function speak(m: ChatMsg) {
    if (!('speechSynthesis' in window)) return
    if (speakingId === m.id) { speechSynthesis.cancel(); setSpeakingId(null); return }
    speechSynthesis.cancel()
    const u = new SpeechSynthesisUtterance(m.content.replace(/[*_#]/g, ''))
    u.onend = () => setSpeakingId(null)
    setSpeakingId(m.id); speechSynthesis.speak(u)
  }

  async function clear() {
    await api('/api/chat/history', { method: 'DELETE' })
    setMsgs([]); speechSynthesis?.cancel?.()
  }

  return (
    <div className="mx-auto flex max-w-3xl flex-col">
      <PageHeader title="AI Health Chat" subtitle="Ask general health questions. Answers are informational only."
        action={<div className="flex items-center gap-2"><ModeBadge mode={ai?.mode} />{msgs.length > 0 && <ConfirmButton onConfirm={clear} message="Clear the whole chat history?"><Trash2 className="h-3.5 w-3.5" /> Clear chat</ConfirmButton>}</div>} />
      <ErrorBox message={error} />

      <div className="card flex h-[60vh] flex-col overflow-y-auto" role="log" aria-live="polite" aria-label="Chat conversation">
        <Bubble role="assistant"><Markdown text={welcome || 'Hello! Welcome to HealthMate AI.'} /></Bubble>
        {msgs.map((m) => (
          <Bubble key={m.id} role={m.role} emergency={!!m.emergency}>
            <Markdown text={m.content} />
            {m.role === 'assistant' && (
              <div className="mt-2 flex flex-wrap items-center gap-2 border-t border-black/10 pt-2 text-[11px] opacity-90">
                <ModeBadge mode={m.mode} />
                {m.mode === 'demo' && <span>{DEMO_NOTE}</span>}
                <button className="ml-auto inline-flex items-center gap-1 underline" onClick={() => speak(m)} aria-label={speakingId === m.id ? 'Stop reading aloud' : 'Read answer aloud'}>
                  {speakingId === m.id ? <VolumeX className="h-3 w-3" /> : <Volume2 className="h-3 w-3" />} {speakingId === m.id ? 'Stop' : 'Listen'}
                </button>
              </div>
            )}
          </Bubble>
        ))}
        {busy && (
          <Bubble role="assistant"><span role="status" aria-label="Assistant is typing" className="inline-flex gap-1">
            {[0, 150, 300].map((d) => <span key={d} className="h-2 w-2 animate-bounce rounded-full bg-slate-400" style={{ animationDelay: `${d}ms` }} />)}
          </span></Bubble>
        )}
        <div ref={endRef} />
      </div>

      <div className="my-3 flex flex-wrap gap-2" aria-label="Suggested questions">
        {SUGGESTED.map((s) => <button key={s} className="chip" disabled={busy} onClick={() => send(s)}>{s}</button>)}
      </div>

      <form onSubmit={(e: FormEvent) => { e.preventDefault(); send(input) }} className="flex gap-2">
        <label htmlFor="chat-input" className="sr-only">Your health question</label>
        <input id="chat-input" className="input" placeholder={listening ? 'Listening…' : 'Type your health question…'} maxLength={1000} value={input} onChange={(e) => setInput(e.target.value)} />
        {Recognition && <button type="button" className={`btn-ghost ${listening ? 'border-red-500 text-red-600' : ''}`} onClick={toggleMic} aria-label={listening ? 'Stop voice input' : 'Start voice input'}><Mic className="h-4 w-4" /></button>}
        <button className="btn-primary" disabled={busy || !input.trim()}><Send className="h-4 w-4" /> Send</button>
      </form>
      <Disclaimer text={disclaimer || undefined} />
    </div>
  )
}

function Bubble({ role, children, emergency }: { role: 'user' | 'assistant'; children: React.ReactNode; emergency?: boolean }) {
  const mine = role === 'user'
  return (
    <div className={`mb-3 flex items-start gap-2 ${mine ? 'flex-row-reverse' : ''}`}>
      <span className={`grid h-8 w-8 shrink-0 place-items-center rounded-full ${mine ? 'bg-sky-100 text-sky-700' : 'bg-teal-100 text-teal-700'}`}>
        {mine ? <UserIcon className="h-4 w-4" /> : <Bot className="h-4 w-4" />}
      </span>
      <div className={`max-w-[85%] rounded-2xl px-4 py-2 text-sm ${
        mine ? 'bg-teal-600 text-white' : emergency ? 'border-2 border-red-500 bg-red-50 text-red-900 dark:bg-red-950/50 dark:text-red-100' : 'bg-slate-100 dark:bg-slate-700'}`}>{children}</div>
    </div>
  )
}
